local directory = assert(os.getenv("VOICEFORGE_ARDOUR_SESSION"))
assert(AudioEngine:set_backend("None (Dummy)", "", ""))
local session = assert(load_session(directory, "VoiceForgeQA"))
local track = session:route_by_name("Voice mono")
assert(not track:isnil())
local processor = track:nth_plugin(0)
assert(not processor:isnil())
local mode = 56
assert(ARDOUR.LuaAPI.set_processor_param(processor, mode, 1.0))
local value, valid = ARDOUR.LuaAPI.get_processor_param(processor, mode)
assert(valid and value == 1.0, "Studio switch did not reach the plugin")
assert(session:save_state("") == 0)
close_session()
print("VoiceForge Ardour Studio export prepared")
